// Entry point
// ---------------------------------------------------------------------------

/**
 * Write (or preview) synthesized changeset files.
 *
 * @param {object} [options]
 * @param {boolean} [options.dryRun] Print instead of writing
 * @param {string} [options.cwd] Repo root (defaults to package root)
 * @param {string} [options.bootstrapSha] Boundary commit overriding detection
 * @returns {Promise<void>}
 */
const main = async ({ dryRun = false, cwd = ROOT, bootstrapSha } = {}) => {
  const git = makeGitRunner(cwd)
  const changesets = await computeChangesets(git, cwd, { bootstrapSha })

  if (changesets.length === 0) {
    log('No dependency changesets to synthesize')
    return
  }

  for (const { filePath, content, pkgNames, sha } of changesets) {
    const rel = path.relative(cwd, filePath)
    const what = `${pkgNames.join(', ')} @ ${sha.slice(0, 7)}`
    if (dryRun) {
      log(`dry-run: would write ${rel} (${what})`)
      console.log(content)
    } else {
      await mkdir(path.dirname(filePath), { recursive: true })
      await writeFile(filePath, content, 'utf8')
      log(`Wrote ${rel} (${what})`)
    }
  }
}

/**
 * Parse command-line flags and run {@link main}. Unknown flags are an error so
 * that a typo like `--dryrun` cannot silently fall through to a real write.
 *
 * @param {string[]} [args] Defaults to `process.argv.slice(2)`
 * @returns {Promise<void>}
 */
const cli = async (args = process.argv.slice(2)) => {
  /** @type {{ 'dry-run': boolean; 'bootstrap-sha'?: string }} */
  let values
  try {
    ;({ values } = parseArgs({
      args,
      options: {
        'dry-run': { type: 'boolean', default: false },
        // Overrides boundary detection entirely
        'bootstrap-sha': { type: 'string' },
      },
      strict: true,
    }))
  } catch (/** @type {any} */ err) {
    log(err)
    process.exitCode = 1
    return
  }
  await main({
    dryRun: values['dry-run'],
    bootstrapSha: values['bootstrap-sha'],
  })
}

if (require.main === module) {
  void cli()
}

